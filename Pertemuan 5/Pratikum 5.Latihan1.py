def pangkat(a, n):
    # base case : jika pangkat 0, hasil = 1
    if n == 0:
        return 1
    
    # recursive case : a × pangkat(a, n-1)
    return a * pangkat(a, n - 1)

print("=======Program Rekursi Pangkat=======")
print(pangkat(2, 4))