# Materi Rekursif L Faktorial
# recursice case => 3! = 3 x 2 x 1
# base case => 0 Berhenti
#=======================================================================================================

def faktorial(n):
    if n == 0: 
        return 1 #base case
    #recirsive case
    return n * faktorial(n-1) 

print("=======Program Faktorial=======")
print("Faktorial dari 5 adalah:", faktorial(5))